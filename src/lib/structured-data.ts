// Pure builders for the JSON-LD structured data every page carries. Kept free
// of Astro imports so they can be unit tested without a build.
//
// Rules the builders keep:
// - Only facts that are shown on the page are described. A fact that is not
//   known yet (`null` in src/lib/site.ts) is left out, never filled in.
// - No ratings, reviews or offers.
// - All addresses are absolute.
//
// A page renders one <script type="application/ld+json"> holding one @graph:
// the business, the home page's WebSite, a breadcrumb trail on nested pages,
// and, on a project page, a description of the project with its photograph.
import type { SiteFacts } from './site';

export type JsonLd = Record<string, unknown>;

const CONTEXT = 'https://schema.org';

/** The business logo: the 512px brand mark generated by `npm run brand`. */
export const LOGO = { path: '/icon-512.png', width: 512, height: 512 } as const;

/** One step of a breadcrumb trail. `path` is root-relative and ends in "/". */
export interface Crumb {
  name: string;
  path: string;
}

export interface ProjectDescription {
  name: string;
  description: string;
  /** Root-relative page path, for example "/portfolio/harbor-house/". */
  path: string;
  /** Town or community as shown on the page. */
  location: string;
  /** The main photograph: any address, resolved against the site. */
  image: { url: string; width: number; height: number; alt: string };
  /** Year the build was finished, when the page shows it. */
  completedYear?: number;
  /** Credited on the page only when the project is marked for it. */
  designPartner?: { name: string; url: string } | null;
}

const origin = (siteUrl: URL | string): string => new URL('/', siteUrl).origin;

/** Absolute address of a page. Always ends in "/" unless the path names a file. */
function absolute(path: string, siteUrl: URL | string): string {
  const url = new URL(path, siteUrl);
  url.search = '';
  url.hash = '';
  if (!url.pathname.split('/').pop()?.includes('.') && !url.pathname.endsWith('/')) {
    url.pathname += '/';
  }
  return url.href;
}

/** The stable identifier other nodes use to point at the business. */
export function businessId(siteUrl: URL | string): string {
  return `${origin(siteUrl)}/#business`;
}

function websiteId(siteUrl: URL | string): string {
  return `${origin(siteUrl)}/#website`;
}

/** Digits to the international form schema.org expects: "5615550100" becomes "+15615550100". */
function internationalPhone(digits: string): string | null {
  const clean = digits.replace(/\D/g, '');
  return clean.length === 10 ? `+1${clean}` : null;
}

/** Keeps only the properties that have a value. */
function compact<T extends JsonLd>(node: T): T {
  return Object.fromEntries(
    Object.entries(node).filter(
      ([, value]) => value !== undefined && value !== null && value !== '',
    ),
  ) as T;
}

/**
 * The business: a GeneralContractor with its name, legal name, office
 * address, area served, address and logo. The phone number and license number
 * are included only when the site publishes them.
 */
export function businessJsonLd(facts: SiteFacts, siteUrl: URL | string): JsonLd {
  const phone = facts.phone ? internationalPhone(facts.phone) : null;
  return compact({
    '@type': 'GeneralContractor',
    '@id': businessId(siteUrl),
    name: facts.name,
    legalName: facts.legalName,
    url: absolute('/', siteUrl),
    description: facts.tagline,
    logo: {
      '@type': 'ImageObject',
      url: new URL(LOGO.path, siteUrl).href,
      width: LOGO.width,
      height: LOGO.height,
    },
    image: new URL(LOGO.path, siteUrl).href,
    address: {
      '@type': 'PostalAddress',
      streetAddress: facts.address.street,
      addressLocality: facts.address.city,
      addressRegion: facts.address.region,
      postalCode: facts.address.postalCode,
      addressCountry: 'US',
    },
    areaServed: facts.serviceArea
      ? { '@type': 'AdministrativeArea', name: facts.serviceArea }
      : undefined,
    telephone: phone ?? undefined,
    identifier: facts.licenseNumber
      ? {
          '@type': 'PropertyValue',
          name: 'State contractor license number',
          value: facts.licenseNumber,
        }
      : undefined,
  });
}

/** The site itself. Search engines read it on the home page to name the site. */
export function websiteJsonLd(facts: SiteFacts, siteUrl: URL | string): JsonLd {
  return {
    '@type': 'WebSite',
    '@id': websiteId(siteUrl),
    name: facts.name,
    url: absolute('/', siteUrl),
    publisher: { '@id': businessId(siteUrl) },
  };
}

/**
 * A breadcrumb trail. Each crumb names a real page with a real address, in
 * order from the home page down to the current page. Returns null for a trail
 * with no steps, so a page can pass nothing and render nothing.
 */
export function breadcrumbJsonLd(crumbs: readonly Crumb[], siteUrl: URL | string): JsonLd | null {
  const steps = crumbs.filter((crumb) => crumb.name.trim() && crumb.path.trim());
  if (steps.length === 0) return null;
  return {
    '@type': 'BreadcrumbList',
    itemListElement: steps.map((crumb, index) => ({
      '@type': 'ListItem',
      position: index + 1,
      name: crumb.name.trim(),
      item: absolute(crumb.path, siteUrl),
    })),
  };
}

const HOME: Crumb = { name: 'Home', path: '/' };

/** Home, a section index, then the page itself. */
function sectionTrail(section: Crumb, page: Crumb): Crumb[] {
  return [HOME, section, page];
}

/** Home › Portfolio › project. */
export function projectCrumbs(title: string, path: string): Crumb[] {
  return sectionTrail({ name: 'Portfolio', path: '/portfolio/' }, { name: title, path });
}

/** Home › Services › service. */
export function serviceCrumbs(title: string, path: string): Crumb[] {
  return sectionTrail({ name: 'Services', path: '/services/' }, { name: title, path });
}

/** Home › Areas We Serve › town. Ready for the town pages. */
export function townCrumbs(name: string, path: string): Crumb[] {
  return sectionTrail({ name: 'Areas We Serve', path: '/areas/' }, { name, path });
}

/**
 * A project page: its name and description, the town it is in, its main
 * photograph and, when the page credits one, the interior design partner.
 */
export function projectJsonLd(project: ProjectDescription, siteUrl: URL | string): JsonLd {
  const url = absolute(project.path, siteUrl);
  const image = {
    '@type': 'ImageObject',
    '@id': `${url}#photo`,
    url: new URL(project.image.url, siteUrl).href,
    width: project.image.width,
    height: project.image.height,
    caption: project.image.alt,
  };
  return compact({
    '@type': 'WebPage',
    '@id': `${url}#project`,
    url,
    name: project.name,
    description: project.description,
    // The WebSite node itself is only on the home page, so name it here by address.
    isPartOf: { '@type': 'WebSite', '@id': websiteId(siteUrl), url: absolute('/', siteUrl) },
    primaryImageOfPage: image,
    image: image.url,
    contentLocation: { '@type': 'Place', name: project.location },
    dateCreated: project.completedYear ? String(project.completedYear) : undefined,
    contributor: project.designPartner
      ? {
          '@type': 'Organization',
          name: project.designPartner.name,
          url: project.designPartner.url,
        }
      : undefined,
  });
}

export interface PageGraphOptions {
  facts: SiteFacts;
  siteUrl: URL | string;
  /** Path of the page being built, used to spot the home page. */
  pathname: string;
  /** Breadcrumb trail for nested pages. Leave out on top-level pages. */
  breadcrumbs?: readonly Crumb[];
  /** Further nodes for this page, such as a project description. */
  nodes?: readonly JsonLd[];
}

/** Everything a page says about itself, as one JSON-LD document. */
export function pageGraph({
  facts,
  siteUrl,
  pathname,
  breadcrumbs = [],
  nodes = [],
}: PageGraphOptions): JsonLd {
  const isHome = absolute(pathname, siteUrl) === absolute('/', siteUrl);
  const trail = breadcrumbJsonLd(breadcrumbs, siteUrl);
  return {
    '@context': CONTEXT,
    '@graph': [
      businessJsonLd(facts, siteUrl),
      ...(isHome ? [websiteJsonLd(facts, siteUrl)] : []),
      ...(trail ? [trail] : []),
      ...nodes,
    ],
  };
}

/**
 * JSON text safe to place inside a <script> element. "<" is escaped so that
 * text such as "</script>" in a project name cannot end the element early;
 * the escaped form is still valid JSON with the same meaning.
 */
export function serializeJsonLd(data: JsonLd): string {
  return JSON.stringify(data).replaceAll('<', '\\u003c');
}
